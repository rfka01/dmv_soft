def baue():
    rom = rom_zeichen()
    for i, ch in enumerate(_dmv00):
        DMV[ch] = rom[i]
    for c in range(0x20, 0x7F):
        DMV[chr(c)] = rom[c]
    for i, ch in enumerate(_dmv80):
        DMV[ch] = rom[0x80 + i]
    g = dict(DMV)
    for ch, t in HAND.items():
        g[ch] = aus_text(t)
    # Akzente aus den ROM-Zeichen: Kleinbuchstaben Zeilen 0-5, Versalien 0-2
    klein = {
        'acute': zeilen(DMV['é'], 0, 5), 'grave': zeilen(DMV['è'], 0, 5),
        'circ': zeilen(DMV['ê'], 0, 5), 'uml': zeilen(DMV['ë'], 0, 5),
        'tilde': zeilen(DMV['ñ'], 0, 5), 'ring': zeilen(DMV['å'], 0, 5),
        'caron': zeilen(DMV['č'], 0, 5),
    }
    gross = {
        'acute': zeilen(DMV['É'], 0, 2), 'circ': zeilen(DMV['Ê'], 0, 2),
        'uml': zeilen(DMV['Ë'], 0, 2), 'tilde': zeilen(DMV['Ñ'], 0, 2),
        'ring': zeilen(DMV['Å'], 0, 2), 'caron': zeilen(DMV['Č'], 0, 2),
    }
    gross['grave'] = spiegeln(gross['acute'])
    punktlos = zeilen(DMV['ì'], 6, 15)          # i ohne Punkt
    def setze(ch, basis, akzent, tab):
        if ch in g:
            return
        b = punktlos if basis == 'ı' else (DMV.get(basis) or g[basis])
        if tab is gross:
            b = zeilen(b, 3, 15)
        else:
            b = zeilen(b, 6, 15) if basis != 'ı' else b
        g[ch] = oder(b, tab[akzent])
    for ch, basis, akz in [
        ('á', 'a', 'acute'), ('í', 'ı', 'acute'), ('ó', 'o', 'acute'), ('ú', 'u', 'acute'),
        ('ý', 'y', 'acute'), ('ÿ', 'y', 'uml'), ('û', 'u', 'circ'), ('ò', 'o', 'grave'),
        ('ù', 'u', 'grave'), ('à', 'a', 'grave'), ('ì', 'ı', 'grave'),
        ('ä', 'a', 'uml'), ('ö', 'o', 'uml'), ('ü', 'u', 'uml'), ('ë', 'e', 'uml'),
        ('â', 'a', 'circ'), ('ô', 'o', 'circ'), ('î', 'ı', 'circ'), ('ï', 'ı', 'uml'),
        ('ã', 'a', 'tilde'), ('õ', 'o', 'tilde'), ('ñ', 'n', 'tilde'), ('å', 'a', 'ring'),
        ('š', 's', 'caron'), ('ž', 'z', 'caron'), ('č', 'c', 'caron')]:
        setze(ch, basis, akz, klein)
    for ch, basis, akz in [
        ('À', 'A', 'grave'), ('Á', 'A', 'acute'), ('Â', 'A', 'circ'), ('Ã', 'A', 'tilde'),
        ('È', 'E', 'grave'), ('Ê', 'E', 'circ'), ('Ë', 'E', 'uml'), ('É', 'E', 'acute'),
        ('Ì', 'I', 'grave'), ('Í', 'I', 'acute'), ('Î', 'I', 'circ'), ('Ï', 'I', 'uml'),
        ('Ò', 'O', 'grave'), ('Ó', 'O', 'acute'), ('Ô', 'O', 'circ'), ('Õ', 'O', 'tilde'),
        ('Ù', 'U', 'grave'), ('Ú', 'U', 'acute'), ('Û', 'U', 'circ'), ('Ÿ', 'Y', 'uml'),
        ('Ý', 'Y', 'acute'), ('Š', 'S', 'caron'), ('Ž', 'Z', 'caron'), ('Ñ', 'N', 'tilde')]:
        setze(ch, basis, akz, gross)
    # weitere Zeichen fuer die TTF (Latin-1)
    if '·' not in g:
        p = leer(); p[7][3] = p[7][4] = p[8][3] = p[8][4] = 1; g['·'] = p
    if '¬' not in g:
        g['¬'] = aus_text('\n'.join(['........'] * 7 + ['.######.', '......#.', '......#.'] + ['........'] * 6))
    if '×' not in g:
        g['×'] = aus_text('\n'.join(['........'] * 5 + ['.#...#..', '..#.#...', '...#....', '..#.#...', '.#...#..'] + ['........'] * 6))
    if '÷' not in g:
        g['÷'] = aus_text('\n'.join(['........'] * 4 + ['...#....', '........', '.#####..', '........', '...#....'] + ['........'] * 7))
    if 'µ' not in g:
        u = [list(r) for r in DMV['u']]
        for r in (12, 13):
            u[r][1] = 1
        g['µ'] = u
    if '¹' not in g:
        g['¹'] = aus_text('\n'.join(['........', '...#....', '..##....', '...#....', '...#....', '..###...'] + ['........'] * 10))
    if '¦' not in g:
        g['¦'] = aus_text('\n'.join(['........'] * 3 + ['...#....'] * 3 + ['........'] * 2 + ['...#....'] * 4 + ['........'] * 4))
    if '¯' not in g:
        g['¯'] = aus_text('\n'.join(['........', '.######.'] + ['........'] * 14))
    if '¸' not in g:
        cs = [list(r) for r in DMV['ç']]
        g['¸'] = zeilen(cs, 12, 15)
    if 'Ð' not in g:
        g['Ð'] = DMV['Đ']
    if 'ð' not in g:
        g['ð'] = DMV['đ']
    return g

