def leer():
    return [[0] * W for _ in range(H)]

def aus_text(t):
    rows = [r for r in t.strip('\n').split('\n')]
    assert len(rows) == H, (len(rows), t)
    return [[1 if ch == '#' else 0 for ch in r.ljust(W, '.')[:W]] for r in rows]

def oder(a, b):
    return [[x | y for x, y in zip(ra, rb)] for ra, rb in zip(a, b)]

def zeilen(g, von, bis):
    return [list(g[r]) if von <= r <= bis else [0] * W for r in range(H)]

def spiegeln(g):
    return [list(reversed(r)) for r in g]

def schieben(g, dx=0, dy=0):
    n = leer()
    for r in range(H):
        for x in range(W):
            if g[r][x] and 0 <= r + dy < H and 0 <= x + dx < W:
                n[r + dy][x + dx] = 1
    return n

